#!/usr/bin/env node
//
// Regenerates the blog hero card artwork in static/assets/media/blog-hero/ from the
// valkey-svgs banner generator (https://github.com/madolson/valkey-svgs). Run it by hand
// when the generator changes; the site build never runs it and needs nothing but Zola.
//
//   git clone https://github.com/madolson/valkey-svgs /tmp/valkey-svgs
//   node build/blog-hero/extract.mjs /tmp/valkey-svgs ["Default Valkey empty.png"]
//
// The optional second argument is the background of the default card, a 1920x1080 PNG that
// madolson made with the logo already in it. It is not part of valkey-svgs, so it is only
// re-encoded when given; without it the committed default-bg.webp and og-plain.webp stay.
//
// Needs Node 22. The og:image rasters also need what valkey-svgs needs: a Chrome-based
// browser and python3 with Pillow. Set PYTHON to pick the interpreter.
//
// Nothing is copied out of the generator's drawing code. Its lib/core.mjs and theme
// modules are imported and called, so the ground, the lockup and the palette are the
// generator's own. The exceptions are in the shield (`pointedShield`): its outline comes to a
// sharper point at the bottom than valkey-svgs' does, and its mark sits higher. Everything is deterministic, so rerunning
// against the same valkey-svgs commit is a no-op diff.
//
// The card itself is composed in templates/macros/blog-hero.html and sass/_blog-hero.scss.
// This script only makes its pieces:
//   ground.svg           the shared background: sky gradient, vignette, film grain
//   lockup.svg           the Valkey mark and wordmark in white, as the corner stamp draws it
//   motif-<key>.svg      a motif, framed around its centre, on a transparent ground
//   og-<key>.webp        the 1200x630 link preview for a card post with that motif
//   default-bg.webp      the default card's background, 1888x1062: twice the widest card
//   og-plain.webp        the default card's link preview: that background, centre-cropped
//   _data/blog-hero/open-sans-400.json
//                        the site's Open Sans advance widths, which the template uses to set
//                        the default card's lines
//   LICENSE, NOTICE      valkey-svgs' Apache-2.0 licence and notice, which cover all of it

import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(SITE, 'static', 'assets', 'media', 'blog-hero');

if (process.argv.length !== 3 && process.argv.length !== 4) {
  console.error('Usage: node build/blog-hero/extract.mjs <path to a valkey-svgs checkout> [default background PNG]');
  process.exit(2);
}
const SVGS = resolve(process.argv[2]);
const DEFAULT_PNG = process.argv[3] && resolve(process.argv[3]);
const load = (...p) => import(pathToFileURL(join(SVGS, ...p)).href);
const G = await load('lib', 'core.mjs');

// The front matter value (`extra.hero_motif`) maps to a generator theme, which supplies the
// art and the og:image framing, and to the change made to that art for the card. `box` is the tile cut out of the
// 1920x1080 drawing grid, centred on the subject with room for its glow.
const MOTIFS = [{ key: 'security', theme: 'security-shield-clean', art: pointedShield, box: [575, 155, 770, 780] }];

const rev = (() => {
  try {
    const sha = execFileSync('git', ['-C', SVGS, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
    const dirty = execFileSync('git', ['-C', SVGS, 'status', '--porcelain'], { encoding: 'utf8' }).trim();
    if (dirty) console.warn(`warning: ${SVGS} has uncommitted changes; the output will not match ${sha}`);
    return dirty ? `${sha}-dirty` : sha;
  } catch {
    console.warn(`warning: ${SVGS} is not a git checkout, so the output cannot name a commit`);
    return 'unknown';
  }
})();

// Apache-2.0 section 4(b) wants changed files to say they were changed.
const notice = (what) =>
  `<!-- ${what}\n` +
  `     Generated by build/blog-hero/extract.mjs from valkey-svgs ${rev}\n` +
  `     (https://github.com/madolson/valkey-svgs). Copyright 2026 The valkey-svgs authors.\n` +
  `     Licensed under the Apache License, Version 2.0: see LICENSE and NOTICE in this directory.\n` +
  `     The Valkey name and mark are trademarks of the Linux Foundation and are not covered by it. -->`;

async function theme(name) {
  const { themes } = await load('themes', `${name}.mjs`);
  const t = themes.find((x) => x.name === name);
  if (!t) throw new Error(`valkey-svgs has no theme named ${name}`);
  return t;
}

// The security shield: valkey-svgs' `security-shield-clean` art, lattice, glow, halo and mark
// as the generator draws them, with two changes madolson asked for.
//
// A sharper point at the bottom. The generator's `shieldPath()` outline is swapped, in all
// five places the art uses it, for `pointedShieldPath()`: the same construction, flat top
// and all, except that the sides start curving at 50% of the height rather than 56% and
// meet at the bottom at 26 degrees below horizontal rather than 18, 3 units lower. Both
// control points of each side stay outside the chord to the tip, which keeps the side
// convex; moving only the second one inward gives an S-bend into a cusp.
//
// The mark sits higher. The shield is wide at the top and tapers below, so its area centroid
// is at y 503, well above its geometric centre, and the generator's mark at 535 reads low.
// The mark and its halo are raised 45 units, to 490, just above the centroid.
const MARK_LIFT = 45;

function pointedShieldPath(cx, cy, w, h, shoulder = 0.5) {
  const n = G.n;
  const hw = w / 2;
  const top = cy - h / 2;
  const bottom = cy + h / 2 + 3;
  const sh = bottom - top;
  const sy = top + sh * shoulder;
  const tipX = hw * 0.5; // the side's last control point, on a 26 degree line into the tip
  const tipY = bottom - tipX * Math.tan((26 * Math.PI) / 180);
  return (
    `M ${n(cx - hw)} ${n(top)} L ${n(cx + hw)} ${n(top)} L ${n(cx + hw)} ${n(sy)} ` +
    `C ${n(cx + hw)} ${n(sy + sh * 0.2)} ${n(cx + tipX)} ${n(tipY)} ${n(cx)} ${n(bottom)} ` +
    `C ${n(cx - tipX)} ${n(tipY)} ${n(cx - hw)} ${n(sy + sh * 0.2)} ${n(cx - hw)} ${n(sy)} Z`
  );
}

function pointedShield(t) {
  const art = t.art(G.rng(t.seed), { text: t.text }, t);
  const flat = /<clipPath id="shieldClean"><path d="([^"]+)"\/>/.exec(art)?.[1];
  const uses = flat ? art.split(`d="${flat}"`).length - 1 : 0;
  if (uses !== 5) throw new Error(`Expected security-shield-clean to draw its outline 5 times, found ${uses}`);
  const shaped = art.split(`d="${flat}"`).join(`d="${pointedShieldPath(960, 545, 570, 580)}"`);
  // Everything from the halo on is the halo and the two passes of the mark.
  const halo = shaped.indexOf('  <circle');
  const tail = shaped.slice(halo);
  if (halo < 0 || !tail.includes('url(#h-mint)') || tail.includes('stroke-width')) {
    throw new Error('Expected security-shield-clean to end with the halo and the mark');
  }
  return `${shaped.slice(0, halo)}  <g transform="translate(0 -${MARK_LIFT})">\n${tail}\n  </g>`;
}

function motifSvg(m, t, art) {
  const [x, y, w, h] = m.box;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${x} ${y} ${w} ${h}">
${notice(`The "${t.name}" art, framed for the blog hero card, changed by extract.mjs in two\n     ways: a sharper point at the bottom than valkey-svgs' shieldPath() draws, and the mark\n     and its halo raised ${MARK_LIFT} units.`)}
${G.defs()}
${art}
</svg>
`;
}

const ground = { title: 'Valkey blog card background', desc: 'The sky gradient, vignette and film grain every Valkey banner sits on.' };

function lockupSvg() {
  const { vw, vh } = G.LOCKUP;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${vw}" height="${vh}" viewBox="0 0 ${vw} ${vh}">
${notice('The Valkey lockup in white, as the corner stamp on every banner draws it.')}
  <g opacity="0.95">${G.lockup(0, 0, vh)}</g>
</svg>
`;
}

// Link previews. A card's title is HTML, which no unfurler can render, so the preview is
// the generator's own banner for the theme with the lockup and no caption: the platforms
// print the post title beside the image anyway.
function ogSvg(t, art) {
  return G.wrap({ ...t, caption: undefined }, art);
}

const PYTHON = process.env.PYTHON ?? 'python3';
// The default card's background and its preview, from madolson's PNG.
const DEFAULT_ENCODE = `
import sys
from PIL import Image
src, bg, og = sys.argv[1], sys.argv[2], sys.argv[3]
im = Image.open(src).convert("RGB")
im.resize((1888, 1062), Image.LANCZOS).save(bg, "WEBP", quality=85, method=6)
keep = round(im.width / (1200 / 630))
top = (im.height - keep) // 2
im.crop((0, top, im.width, top + keep)).resize((1200, 630), Image.LANCZOS).save(og, "WEBP", quality=90, method=6)
`;

const ENCODE = `
import sys
from PIL import Image
src, dst = sys.argv[1], sys.argv[2]
im = Image.open(src).convert("RGB")
keep = round(im.width / (1200 / 630))
top = (im.height - keep) // 2
im.crop((0, top, im.width, top + keep)).resize((1200, 630), Image.LANCZOS).save(dst, "WEBP", quality=90, method=6)
`;

function findChrome() {
  const found = [
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/Applications/Chromium.app/Contents/MacOS/Chromium',
    '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',
    '/usr/bin/google-chrome',
    '/usr/bin/chromium',
  ].find((p) => existsSync(p));
  if (!found) throw new Error('The og:image rasters need a Chrome-based browser and none was found.');
  return found;
}

function rasterise(chrome, scratch, key, svg) {
  const svgPath = join(scratch, `og-${key}.svg`);
  const pngPath = join(scratch, `og-${key}.png`);
  writeFileSync(svgPath, svg);
  execFileSync(
    chrome,
    ['--headless', '--disable-gpu', '--hide-scrollbars', `--window-size=${G.W},${G.H}`, `--screenshot=${pngPath}`, pathToFileURL(svgPath).href],
    { stdio: 'ignore' }
  );
  execFileSync(PYTHON, ['-c', ENCODE, pngPath, join(OUT, `og-${key}.webp`)], { stdio: ['ignore', 'ignore', 'inherit'] });
}

// The default card's template sets its own lines (blog_hero.fit), so it needs to know how
// wide the text is. These are Open Sans 400's advance widths, in em, measured in Chrome from
// the site's own font files, for printable ASCII and the punctuation and accents titles use.
// The template counts anything else as 0.6em.
const GLYPHS = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), ...'’‘“”–—…×éèüöäñç'];

function measureOpenSans(chrome, scratch) {
  const css = pathToFileURL(join(SITE, 'static', 'fonts', 'open-sans', 'webfont.css')).href;
  const page = join(scratch, 'glyphs.html');
  writeFileSync(page, `<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="${css}"></head>
<body><pre id="out"></pre><script>
const chars = ${JSON.stringify(GLYPHS)};
document.fonts.load('400 100px "Open Sans"', chars.join('')).then(() => {
  const c = document.createElement('canvas').getContext('2d');
  c.font = '400 1000px "Open Sans"';
  const out = { loaded: document.fonts.check('400 100px "Open Sans"') };
  for (const ch of chars) out[ch] = Math.round(c.measureText(ch).width) / 1000;
  document.getElementById('out').textContent = JSON.stringify(out);
});
</script></body></html>`);
  const dom = execFileSync(
    chrome,
    ['--headless', '--disable-gpu', '--allow-file-access-from-files', '--virtual-time-budget=10000', '--dump-dom', pathToFileURL(page).href],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }
  );
  const raw = /<pre id="out">([^<]*)<\/pre>/.exec(dom)?.[1];
  if (!raw) throw new Error('Could not measure Open Sans: the page did not report widths.');
  const widths = JSON.parse(raw.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&'));
  if (!widths.loaded) throw new Error('Could not measure Open Sans: the font did not load, so the widths would be a fallback font\'s.');
  delete widths.loaded;
  const sorted = Object.fromEntries(Object.keys(widths).sort().map((k) => [k, widths[k]]));
  mkdirSync(join(SITE, '_data', 'blog-hero'), { recursive: true });
  writeFileSync(join(SITE, '_data', 'blog-hero', 'open-sans-400.json'), `${JSON.stringify(sorted, null, 1)}\n`);
}

mkdirSync(OUT, { recursive: true });
const chrome = findChrome();
const scratch = mkdtempSync(join(tmpdir(), 'blog-hero-'));
try {
  writeFileSync(join(OUT, 'ground.svg'), G.wrap(ground, notice('The shared ground of every Valkey banner.'), { chrome: false }));
  writeFileSync(join(OUT, 'lockup.svg'), lockupSvg());
  if (DEFAULT_PNG) {
    execFileSync(PYTHON, ['-c', DEFAULT_ENCODE, DEFAULT_PNG, join(OUT, 'default-bg.webp'), join(OUT, 'og-plain.webp')], {
      stdio: ['ignore', 'ignore', 'inherit'],
    });
  }
  for (const m of MOTIFS) {
    const t = await theme(m.theme);
    const art = m.art(t);
    writeFileSync(join(OUT, `motif-${m.key}.svg`), motifSvg(m, t, art));
    rasterise(chrome, scratch, m.key, ogSvg(t, art));
    console.log(`${m.key.padEnd(14)} <- ${m.theme}`);
  }
  for (const f of ['LICENSE', 'NOTICE']) copyFileSync(join(SVGS, f), join(OUT, f));
  measureOpenSans(chrome, scratch);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
console.log(`wrote ${OUT} from valkey-svgs ${rev}`);
